-- 166. Согласие с условиями использования как факт, а не как состояние браузера.
--
-- До этой миграции галочка на странице регистрации проверялась только клиентом: `POST /register`
-- принимал запрос без неё, и доказать согласие конкретного пользователя было нечем.
-- Раздел 164.
--
-- Идемпотентна: повторный запуск ничего не меняет.

alter table public.users
  add column if not exists terms_accepted_at timestamptz;

comment on column public.users.terms_accepted_at is
  'Момент, когда пользователь подтвердил согласие с условиями использования и политикой конфиденциальности. Заполняется сервером при регистрации (миграция 166).';
